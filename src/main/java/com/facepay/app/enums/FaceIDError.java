package com.facepay.app.enums;

import lombok.Getter;

/**
 * Коды ошибок для платежей через FaceID
 * <p>
 * Охватывает все типы ошибок, которые могут возникнуть при биометрической аутентификации:
 * - Ошибки биометрии (не распознано, мошенничество, плохое качество)
 * - Бизнес-ошибки (недостаточно средств, отключена услуга, лимиты)
 * - Технические ошибки (сбой камеры, таймаут, потеря связи)
 * </p>
 */
@Getter
public enum FaceIDError {
    // === Ошибки биометрии (Проблемы с распознаванием лица) ===
    
    /**
     * Пользователь не найден - лицо отсканировано, но система не нашла биометрический слепок
     */
    FACE_NOT_RECOGNIZED("Пользователь не найден", "Лицо отсканировано, но система не нашла биометрический слепок в базе"),
    
    /**
     * Попытка мошенничества - алгоритмы Liveness определили, что перед камерой фото/видео/маска
     */
    SPOOFING_ATTACK_DETECTED("Попытка мошенничества", "Алгоритмы Liveness определили фальшивое изображение"),
    
    /**
     * Плохое качество кадра - грязная камера, слишком темно или засветка
     */
    POOR_LIGHTING_OR_QUALITY("Плохое качество кадра", "Камера грязная, слишком темно или засветка"),
    
    /**
     * Лицо закрыто - солнцезащитные очки, медицинская маска или капюшон
     */
    FACE_OCCLUSION("Лицо закрыто", "Солнцезащитные очки, медицинская маска или капюшон"),
    
    // === Бизнес-ошибки и проблемы со счетом ===
    
    /**
     * Недостаточно средств - лицо распознано, но на счете не хватает денег
     */
    INSUFFICIENT_FUNDS("Недостаточно средств", "Лицо распознано, но на счете не хватает денег для списания"),
    
    /**
     * Услуга отключена - клиент отозвал согласие на обработку биометрии
     */
    BIOMETRIC_SERVICE_DISABLED("Услуга отключена", "Клиент отозвал согласие на обработку биометрии"),
    
    /**
     * Лимит превышен - сумма покупки превышает лимит для биометрических операций
     */
    LIMIT_EXCEEDED("Лимит превышен", "Сумма превышает лимит для биометрических операций без ПИН"),
    
    // === Технические и инфраструктурные ошибки ===
    
    /**
     * Сбой оборудования камеры - камера на терминале повреждена или не отвечает
     */
    TERMINAL_CAMERA_HARDWARE_FAULT("Сбой оборудования камеры", "Камера на терминале повреждена или не отвечает"),
    
    /**
     * Таймаут сервера биометрии - центральный сервер не ответил за 3-5 секунд
     */
    BIOMETRIC_ENGINE_TIMEOUT("Таймаут сервера биометрии", "Центральный сервер не ответил за 3-5 секунд"),
    
    /**
     * Проблемы со связью - терминал потерял интернет (Wi-Fi/GSM)
     */
    NETWORK_DISCONNECTION("Проблемы со связью", "Терминал потерял интернет (Wi-Fi/GSM)");
    
    private final String shortDescription;
    private final String detailedDescription;
    
    FaceIDError(String shortDescription, String detailedDescription) {
        this.shortDescription = shortDescription;
        this.detailedDescription = detailedDescription;
    }

    @Override
    public String toString() {
        return shortDescription;
    }
    
    /**
     * Получить enum по коду ошибки (для десериализации из JSON)
     */
    public static FaceIDError fromCode(String code) {
        if (code == null) {
            return null;
        }
        try {
            return FaceIDError.valueOf(code);
        } catch (IllegalArgumentException e) {
            return null;
        }
    }
}
